"""Run the eval harness three times — once per retrieval mode — and emit a
markdown table to stdout (and to ``eval/results_modes.md``).

The script relies on the per-request ``retrieve_mode`` override added in
v0.3.0, so you don't have to restart the server with a different
``RETRIEVE_MODE`` env var between runs.

Usage::

    python eval/run_eval_modes.py --base-url http://localhost:8000 --top-k 5
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from run_eval import evaluate

MODES = ("vector", "bm25", "hybrid")
OUT_PATH = Path(__file__).parent / "results_modes.md"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-url", default="http://localhost:8000")
    parser.add_argument("--top-k", type=int, default=5)
    parser.add_argument(
        "--out",
        type=Path,
        default=OUT_PATH,
        help="Where to write the markdown table (default: eval/results_modes.md).",
    )
    args = parser.parse_args(argv)

    print(f"Running eval against {args.base_url} for modes: {', '.join(MODES)}")
    rows: dict[str, dict[str, float]] = {}
    for mode in MODES:
        print(f"  → mode={mode}")
        rows[mode] = evaluate(args.base_url, args.top_k, mode)

    table = render_table(rows, top_k=args.top_k)
    args.out.write_text(table, encoding="utf-8")
    print()
    print(table)
    print(f"\nWrote {args.out}")
    return 0


def render_table(rows: dict[str, dict[str, float]], *, top_k: int) -> str:
    recall_key = f"recall@{top_k}"
    headers = ["mode", recall_key, "citation_acc", "keyword_coverage", "p50 ms", "p95 ms"]
    md = ["<!-- generated by eval/run_eval_modes.py — do not edit by hand -->", ""]
    md.append("| " + " | ".join(headers) + " |")
    md.append("| " + " | ".join(["---"] * len(headers)) + " |")

    for mode, m in rows.items():
        md.append(
            "| "
            + " | ".join(
                [
                    f"`{mode}`",
                    f"{m[recall_key]:.3f}",
                    f"{m['citation_acc']:.3f}",
                    f"{m['keyword_coverage']:.3f}",
                    f"{m['latency_p50_ms']:.0f}",
                    f"{m['latency_p95_ms']:.0f}",
                ]
            )
            + " |"
        )

    md.append("")
    md.append(f"_n = {int(next(iter(rows.values()))['n'])} questions, top_k = {top_k}._")
    return "\n".join(md) + "\n"


if __name__ == "__main__":
    sys.exit(main())
